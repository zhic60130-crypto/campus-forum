CREATE TABLE IF NOT EXISTS account (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username      VARCHAR(64)  NOT NULL UNIQUE,
    email         VARCHAR(128) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL,
    avatar        VARCHAR(512) DEFAULT '',
    bio           VARCHAR(500) DEFAULT '',
    role          VARCHAR(32)  NOT NULL DEFAULT 'USER',
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS category (
    id        VARCHAR(32) PRIMARY KEY,
    label     VARCHAR(64)  NOT NULL,
    color     VARCHAR(32)  NOT NULL,
    icon      VARCHAR(64)  NOT NULL,
    desc_text VARCHAR(255),
    sort      INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS tag (
    id    VARCHAR(32) PRIMARY KEY,
    label VARCHAR(64) NOT NULL
);

CREATE TABLE IF NOT EXISTS topic (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id      BIGINT       NOT NULL,
    title          VARCHAR(200) NOT NULL,
    content        TEXT         NOT NULL,
    category_id    VARCHAR(32)  NOT NULL,
    images_json    VARCHAR(2000),
    like_count     INT          NOT NULL DEFAULT 0,
    favorite_count INT          NOT NULL DEFAULT 0,
    created_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at     TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS topic_tag (
    topic_id BIGINT      NOT NULL,
    tag_id   VARCHAR(32) NOT NULL,
    PRIMARY KEY (topic_id, tag_id)
);

CREATE TABLE IF NOT EXISTS topic_comment (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id      BIGINT       NOT NULL,
    author_id     BIGINT       NOT NULL,
    content       TEXT         NOT NULL,
    parent_id     BIGINT,
    reply_to_name VARCHAR(64),
    like_count    INT          NOT NULL DEFAULT 0,
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS interact (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL,
    target_id   BIGINT      NOT NULL,
    target_type VARCHAR(32) NOT NULL,
    action_type VARCHAR(32) NOT NULL,
    created_at  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_interact ON interact(user_id, target_id, target_type, action_type);

CREATE TABLE IF NOT EXISTS banner (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title      VARCHAR(128) NOT NULL,
    subtitle   VARCHAR(255) DEFAULT '',
    image_url  VARCHAR(512) NOT NULL,
    link       VARCHAR(512) DEFAULT '',
    enabled    BOOLEAN      NOT NULL DEFAULT TRUE,
    sort       INT          NOT NULL DEFAULT 0,
    created_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS announcement (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    content VARCHAR(512) NOT NULL,
    sort    INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS friend_link (
    id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(64)  NOT NULL,
    url  VARCHAR(512) NOT NULL,
    sort INT NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS topic_report (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_id      BIGINT       NOT NULL,
    topic_title   VARCHAR(200) NOT NULL,
    reporter_id   BIGINT       NOT NULL,
    reporter_name VARCHAR(64)  NOT NULL,
    reason        VARCHAR(32)  NOT NULL,
    detail        VARCHAR(500) DEFAULT '',
    status        VARCHAR(32)  NOT NULL DEFAULT 'PENDING',
    admin_id      BIGINT,
    admin_note    VARCHAR(500) DEFAULT '',
    created_at    TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at   TIMESTAMP
);

CREATE UNIQUE INDEX IF NOT EXISTS uk_report_reporter_topic ON topic_report(reporter_id, topic_id);
CREATE INDEX IF NOT EXISTS idx_report_status ON topic_report(status, created_at);
